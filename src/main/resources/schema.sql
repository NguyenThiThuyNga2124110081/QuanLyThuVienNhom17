CREATE TABLE IF NOT EXISTS TheLoai (
    maTL VARCHAR(10) PRIMARY KEY,
    tenTL VARCHAR(50) NOT NULL,
    moTa VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS NhaXuatBan (
    maNXB VARCHAR(10) PRIMARY KEY,
    tenNXB VARCHAR(100) NOT NULL,
    diaChi VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS TacGia (
    maTG VARCHAR(10) PRIMARY KEY,
    tenTG VARCHAR(100) NOT NULL,
    quocTich VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS TaiKhoan (
    maTK VARCHAR(10) PRIMARY KEY,
    tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    matKhau VARCHAR(255) NOT NULL,
    hoTen VARCHAR(100) NOT NULL,
    vaiTro VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS DocGia (
    maDG VARCHAR(10) PRIMARY KEY,
    hoTen VARCHAR(100) NOT NULL,
    ngaySinh DATE,
    soDienThoai VARCHAR(15) UNIQUE,
    email VARCHAR(100) UNIQUE,
    diaChi VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS Sach (
    maSach VARCHAR(10) PRIMARY KEY,
    tenSach VARCHAR(200) NOT NULL,
    maTL VARCHAR(10) NOT NULL REFERENCES TheLoai(maTL),
    maNXB VARCHAR(10) NOT NULL REFERENCES NhaXuatBan(maNXB),
    namXuatBan INT,
    soLuong INT NOT NULL DEFAULT 0 CHECK (soLuong >= 0)
);

CREATE TABLE IF NOT EXISTS Sach_TacGia (
    maSach VARCHAR(10) NOT NULL REFERENCES Sach(maSach) ON DELETE CASCADE,
    maTG VARCHAR(10) NOT NULL REFERENCES TacGia(maTG),
    PRIMARY KEY (maSach, maTG)
);

CREATE TABLE IF NOT EXISTS PhieuNhap (
    maPN VARCHAR(10) PRIMARY KEY,
    maTK VARCHAR(10) NOT NULL REFERENCES TaiKhoan(maTK),
    ngayNhap DATE NOT NULL,
    ghiChu VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS ChiTietPhieuNhap (
    maPN VARCHAR(10) NOT NULL REFERENCES PhieuNhap(maPN) ON DELETE CASCADE,
    maSach VARCHAR(10) NOT NULL REFERENCES Sach(maSach),
    soLuong INT NOT NULL CHECK (soLuong > 0),
    donGia INT NOT NULL CHECK (donGia >= 0),
    PRIMARY KEY (maPN, maSach)
);

CREATE TABLE IF NOT EXISTS PhieuMuon (
    maPM VARCHAR(10) PRIMARY KEY,
    maDG VARCHAR(10) NOT NULL REFERENCES DocGia(maDG),
    maTK VARCHAR(10) NOT NULL REFERENCES TaiKhoan(maTK),
    ngayMuon DATE NOT NULL,
    hanTra DATE NOT NULL,
    trangThai VARCHAR(20) NOT NULL DEFAULT 'Đang mượn'
);

CREATE TABLE IF NOT EXISTS ChiTietPhieuMuon (
    maPM VARCHAR(10) NOT NULL REFERENCES PhieuMuon(maPM) ON DELETE CASCADE,
    maSach VARCHAR(10) NOT NULL REFERENCES Sach(maSach),
    soLuong INT NOT NULL CHECK (soLuong > 0),
    ngayTra DATE,
    tienPhat INT NOT NULL DEFAULT 0 CHECK (tienPhat >= 0),
    PRIMARY KEY (maPM, maSach)
);

CREATE INDEX IF NOT EXISTS idx_sach_ten ON Sach(tenSach);
CREATE INDEX IF NOT EXISTS idx_phieumuon_docgia ON PhieuMuon(maDG);
